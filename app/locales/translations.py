def t(key: str, lang: str = "en") -> str:
    """Translate a key to the given language. Fallback to English."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return lang_dict.get(key, TRANSLATIONS["en"].get(key, key))


def get_current_language() -> str:
    """Read the current language from the DB settings."""
    from app.db.database import get_connection
    conn = get_connection()
    row = conn.execute(
        "SELECT value FROM settings WHERE key = 'language'"
    ).fetchone()
    conn.close()
    return row["value"] if row else "en"


def set_setting(key: str, value: str) -> None:
    """Save a setting to the DB."""
    from app.db.database import get_connection
    conn = get_connection()
    conn.execute("""
        INSERT INTO settings (key, value) VALUES (?, ?)
        ON CONFLICT(key) DO UPDATE SET value = excluded.value
    """, (key, value))
    conn.commit()
    conn.close()


def get_setting(key: str, default: str = "") -> str:
    """Read a setting from the DB."""
    from app.db.database import get_connection
    conn = get_connection()
    row = conn.execute(
        "SELECT value FROM settings WHERE key = ?", (key,)
    ).fetchone()
    conn.close()
    return row["value"] if row else default
 


def currency(lang: str = "en") -> str:
    """Return the localized currency display string."""
    return t("currency_display", lang)
